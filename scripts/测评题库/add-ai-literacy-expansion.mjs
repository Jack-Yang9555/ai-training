function objective({
  id,
  type,
  dimension,
  primaryTag,
  crossTags = [],
  difficulty,
  stem,
  options,
  correct,
  explanation,
  estimatedMinutes,
}) {
  return {
    id,
    scope: "common",
    branch: null,
    type,
    dimension,
    tags: [primaryTag, ...crossTags],
    difficulty,
    stem,
    options,
    answer: correct.map((index) => options[index]),
    explanation,
    score: type === "多选" || type === "情境判断" ? 2 : 1,
    estimatedMinutes: estimatedMinutes ?? (type === "情境判断" ? 1.5 : type === "多选" ? 1 : 0.5),
    primaryTag,
  };
}

function judgment({ id, dimension, primaryTag, crossTags = [], stem, correct, explanation }) {
  return objective({
    id,
    type: "判断",
    dimension,
    primaryTag,
    crossTags,
    difficulty: "L1",
    stem,
    options: ["正确", "错误"],
    correct: [correct ? 0 : 1],
    explanation,
  });
}

function practical({
  id,
  dimension,
  difficulty,
  crossTags = [],
  stem,
  answer,
  explanation,
  materials,
  toolGuidance,
  steps,
  completionItems,
}) {
  return {
    id,
    scope: "common",
    branch: null,
    type: "实操",
    dimension,
    tags: ["真实操作与成果验证", ...crossTags],
    difficulty,
    stem,
    options: [],
    answer,
    explanation,
    score: 5,
    rubricId: "practical-5",
    practicalSpec: {
      materials,
      toolGuidance,
      steps,
      completionItems,
    },
    estimatedMinutes: difficulty === "L2" ? 10 : 12,
    primaryTag: "真实操作与成果验证",
  };
}

